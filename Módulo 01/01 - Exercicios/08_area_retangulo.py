"""
Crie duas variáveis:

largura
altura

Calcule:

área = largura × altura

Apresente largura, altura e área.
"""

# Definindo as variáveis
largura = 5
altura = 10

# Calculando a área
area = largura * altura

# Apresentando os valores
print("Largura:", largura, "cm")
print("Altura:", altura, "cm")
print("Área:", area, "cm²")

