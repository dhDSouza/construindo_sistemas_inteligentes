""" 
Considere:

1 hora = 60 minutos

Crie uma variável:

horas = 7

Calcule através do programa quantos minutos existem nesse período.

Resultado esperado:

7 horas equivalem a 420 minutos
"""

# Inicializando a variável
horas = 7

# Calculando o total de minutos
minutos = horas * 60

# Exibindo o resultado
print(f"{horas} horas equivalem a {minutos} minutos")

# Explicação do código:

"""
O código acima realiza a conversão de horas para minutos. 
Inicialmente, é definida a variável `horas` com o valor 7. 
Em seguida, o total de minutos é calculado multiplicando o número de horas por 60, já que cada hora possui 60 minutos. 
Por fim, o resultado é exibido na tela utilizando a função `print` com uma f-string para formatar a saída de forma clara e legível, mostrando quantos minutos correspondem ao período de horas especificado.
"""