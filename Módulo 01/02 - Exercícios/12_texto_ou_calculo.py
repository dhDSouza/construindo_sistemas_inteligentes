# Exercício 12 — Texto ou cálculo?

# Previsão: mostra 12 + 3, pois o conteúdo entre aspas é texto literal.
print("12 + 3")

# Previsão: mostra 15, pois Python calcula a soma dos números.
print(12 + 3)

# Previsão: mostra Resultado: 15; a vírgula separa os argumentos do print().
print("Resultado:", 12 + 3)

# Previsão: mostra 12 3, com um espaço entre os dois textos.
print("12", "3")

# As duas primeiras linhas diferem porque as aspas indicam texto (str).
# Sem aspas, 12 + 3 é uma expressão aritmética que Python calcula.
